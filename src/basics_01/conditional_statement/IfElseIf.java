package basics_01.conditional_statement;

public class IfElseIf {


    public static void main(String[] args) {
        int a=5;
        int b=7;
        int c=9;

        if(a>b){
            System.out.println(a);
        }else if(b>c){
            System.out.println(b);
        }else{
            System.out.println(c);
        }
    }

}
